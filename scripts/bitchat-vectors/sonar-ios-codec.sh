#!/usr/bin/env bash
# Build a throwaway Swift package from Sonar iOS's OWN bitchat codec files
# (ios/bitchat/...), so the wire format the app ships can be exercised with
# `swift test` -- no app target, no simulator, no Breez/Firebase packages.
#
#   scripts/bitchat-vectors/sonar-ios-codec.sh <dir> [extra test file ...]
#
# The files are copied verbatim from this checkout; only two app-level
# dependencies are replaced: MessageType/NoisePayloadType are cut out of
# BitchatProtocol.swift (whose delegate protocol pulls in CoreBluetooth), and
# TransportConfig is reduced to the constants the codec reads, with their
# values taken from the real file. BitLogger is the in-repo package.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
APP="$ROOT/ios/bitchat"
DIR="${1:?usage: sonar-ios-codec.sh <dir> [extra test file ...]}"
shift
SRC="$DIR/Sources/SonarIOSCodec"
TESTS="$DIR/Tests/SonarIOSCodecTests"
rm -rf "$DIR"
mkdir -p "$SRC" "$TESTS"

# The codec: packet frame, compression, padding, signatures, peer ids and
# every TLV the mesh carries. Keep this list in step with what BLEService
# encodes and decodes.
for f in \
  Protocols/BinaryProtocol.swift Protocols/BinaryEncodingUtils.swift \
  Protocols/BitchatFilePacket.swift Protocols/Packets.swift Protocols/FragmentHeader.swift Protocols/PacketPayloadLimits.swift \
  Models/BitchatPacket.swift Models/NoisePayload.swift Models/MessagePadding.swift Models/PeerID.swift \
  Utils/CompressionUtil.swift Utils/FileTransferLimits.swift Utils/Data+SHA256.swift; do
  cp "$APP/$f" "$SRC/"
done

python3 - "$APP/Protocols/BitchatProtocol.swift" "$APP/Services/TransportConfig.swift" "$SRC" <<'PY'
import re, sys
proto, tconf, out = sys.argv[1], sys.argv[2], sys.argv[3]
src = open(proto).read()
start = src.index("enum MessageType")
end = src.index("enum LazyHandshakeState")
open(f"{out}/MessageTypes.swift", "w").write("import Foundation\n\n" + src[start:end].rstrip() + "\n")
cfg = open(tconf).read()
need = ["compressionThresholdBytes", "nostrConvKeyPrefixLength", "nostrShortKeyDisplayLength"]
lines = []
for n in need:
    m = re.search(rf"^\s*static let {n}\s*:[^=]+=\s*[^\n]+", cfg, re.M)
    if not m:
        sys.exit(f"TransportConfig.{n} not found in {tconf}")
    lines.append("    " + m.group(0).strip())
open(f"{out}/TransportConfigSubset.swift", "w").write(
    "// Subset of ios/bitchat/Services/TransportConfig.swift (values copied by sonar-ios-codec.sh).\n"
    "enum TransportConfig {\n" + "\n".join(lines) + "\n}\n")
PY

for t in "$@"; do cp "$t" "$TESTS/"; done

cat > "$DIR/Package.swift" <<EOF
// swift-tools-version: 5.9
// Generated by scripts/bitchat-vectors/sonar-ios-codec.sh -- do not edit.
import PackageDescription

let package = Package(
    name: "SonarIOSCodec",
    platforms: [.macOS(.v13)],
    dependencies: [.package(path: "$ROOT/ios/localPackages/BitLogger")],
    targets: [
        .target(name: "SonarIOSCodec", dependencies: ["BitLogger"], path: "Sources/SonarIOSCodec"),
        .testTarget(name: "SonarIOSCodecTests", dependencies: ["SonarIOSCodec"], path: "Tests/SonarIOSCodecTests",
                    swiftSettings: [.define("SONAR_IOS")])
    ]
)
EOF
echo "sonar-ios codec package: $DIR"
